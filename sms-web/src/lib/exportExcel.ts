import * as XLSX from "xlsx";

export interface ExcelColumn<T = Record<string, unknown>> {
  key: keyof T | string;
  label: string;
  width?: number;
  format?: (value: unknown, item: T) => string | number | boolean | null | undefined;
}

export interface SingleSheetExportOptions<T extends object = Record<string, unknown>> {
  filename: string;
  sheetName?: string;
  columns: ExcelColumn<T>[];
  data: T[];
  title?: string;
  subtitle?: string;
  metadata?: Record<string, string | number>;
}

export interface ExcelSheetDefinition<T extends object = Record<string, unknown>> {
  sheetName: string;
  columns: ExcelColumn<T>[];
  data: T[];
  title?: string;
  subtitle?: string;
  metadata?: Record<string, string | number>;
}

export interface MultiSheetExportOptions {
  filename: string;
  sheets: ExcelSheetDefinition<any>[];
}

/**
 * Builds an XLSX Worksheet from columns, data, optional title and metadata headers.
 */
function buildWorksheet<T extends object>(sheetDef: ExcelSheetDefinition<T>): XLSX.WorkSheet {
  const rows: (string | number | boolean | null | undefined)[][] = [];

  // Title & Subtitle block
  if (sheetDef.title) {
    rows.push([sheetDef.title]);
    if (sheetDef.subtitle) {
      rows.push([sheetDef.subtitle]);
    }
    rows.push([]); // blank separator
  }

  // Metadata block (e.g. As of Date, Store, Generated By)
  if (sheetDef.metadata && Object.keys(sheetDef.metadata).length > 0) {
    Object.entries(sheetDef.metadata).forEach(([k, v]) => {
      rows.push([k, v]);
    });
    rows.push([]); // blank separator
  }

  // Column Headers
  const headerRow = sheetDef.columns.map((c) => c.label);
  rows.push(headerRow);

  // Data Rows
  sheetDef.data.forEach((item) => {
    const row = sheetDef.columns.map((col) => {
      const rawValue = (item as Record<string, unknown>)[col.key as string];
      if (col.format) {
        return col.format(rawValue, item);
      }
      if (rawValue === null || rawValue === undefined) {
        return "";
      }
      if (typeof rawValue === "number" || typeof rawValue === "boolean") {
        return rawValue;
      }
      if (typeof rawValue === "object") {
        return JSON.stringify(rawValue);
      }
      return String(rawValue);
    });
    rows.push(row);
  });

  const ws = XLSX.utils.aoa_to_sheet(rows);

  // Column auto-sizing based on header label length or custom width
  ws["!cols"] = sheetDef.columns.map((col) => {
    if (col.width) {
      return { wch: col.width };
    }
    const maxContentLen = sheetDef.data.reduce((max, item) => {
      const val = (item as Record<string, unknown>)[col.key as string];
      const str = val !== null && val !== undefined ? String(val) : "";
      return Math.max(max, str.length);
    }, col.label.length);
    return { wch: Math.min(Math.max(maxContentLen + 3, 12), 50) };
  });

  return ws;
}

/**
 * Trigger browser file download from an XLSX workbook.
 */
function triggerWorkbookDownload(wb: XLSX.WorkBook, filename: string): void {
  const cleanName = filename.endsWith(".xlsx") ? filename : `${filename}.xlsx`;
  const excelBuffer = XLSX.write(wb, { bookType: "xlsx", type: "array" });
  const blob = new Blob([excelBuffer], {
    type: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet;charset=UTF-8",
  });

  const url = window.URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.setAttribute("href", url);
  link.setAttribute("download", cleanName);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  window.URL.revokeObjectURL(url);
}

/**
 * Export single-sheet tabular data to an Excel (.xlsx) file.
 */
export function exportToExcel<T extends object>(options: SingleSheetExportOptions<T>): void {
  const { filename, sheetName = "Sheet1", ...rest } = options;
  if (!rest.data || rest.data.length === 0) {
    alert("No data available to export.");
    return;
  }

  const wb = XLSX.utils.book_new();
  const ws = buildWorksheet({ sheetName, ...rest });
  XLSX.utils.book_append_sheet(wb, ws, sheetName.slice(0, 31)); // Excel 31 char sheet limit
  triggerWorkbookDownload(wb, filename);
}

/**
 * Export multi-sheet tabular data to an Excel (.xlsx) workbook.
 */
export function exportMultiSheetExcel(options: MultiSheetExportOptions): void {
  const { filename, sheets } = options;
  if (!sheets || sheets.length === 0) {
    alert("No sheets provided for export.");
    return;
  }

  const wb = XLSX.utils.book_new();
  sheets.forEach((sheet) => {
    const ws = buildWorksheet(sheet);
    XLSX.utils.book_append_sheet(wb, ws, sheet.sheetName.slice(0, 31));
  });

  triggerWorkbookDownload(wb, filename);
}

/**
 * Specialized Excel Workbook Exporter: Financial Aging & Portfolio Report
 */
export interface FinancialAgingExportParams {
  storeName?: string;
  asOfDate?: string;
  summary: {
    totalReceivableBalance: number;
    totalOverdueBalance: number;
    totalCollectedCash: number;
    custodyDiscrepanciesCount?: number;
  };
  buckets: Array<{
    bucketName: string;
    installmentCount: number;
    totalAmount: number;
    percentage: number;
  }>;
  receivables: Array<{
    receivableNumber: string;
    customerName: string;
    customerPhone?: string;
    storeName?: string;
    financedAmount: number;
    totalPaid: number;
    remainingBalance: number;
    paymentTermMonths: number;
    status: string;
    firstDueDate?: string | null;
  }>;
}

export function exportFinancialAgingToExcel(params: FinancialAgingExportParams): void {
  const asOf = params.asOfDate || new Date().toISOString().substring(0, 10);
  const storeScope = params.storeName || "Company Wide (All Stores)";

  // Sheet 1: Aging Portfolio Summary
  const summaryMetadata: Record<string, string | number> = {
    "Report Name": "Credit Receivables Portfolio & Aging Analysis",
    "Generated As Of": asOf,
    "Store Scope": storeScope,
    "Total Active Portfolio (IDR)": params.summary.totalReceivableBalance,
    "Total Overdue Balance (IDR)": params.summary.totalOverdueBalance,
    "Total Collected Cash (IDR)": params.summary.totalCollectedCash,
    "Cash Custody Discrepancies Flagged": params.summary.custodyDiscrepanciesCount ?? 0,
  };

  const bucketColumns: ExcelColumn<(typeof params.buckets)[0]>[] = [
    { key: "bucketName", label: "Aging Delinquency Bucket", width: 28 },
    { key: "installmentCount", label: "Installment Count", width: 18 },
    {
      key: "totalAmount",
      label: "Outstanding Balance (IDR)",
      width: 25,
      format: (val) => Number(val ?? 0),
    },
    {
      key: "percentage",
      label: "Portfolio Share (%)",
      width: 18,
      format: (val) => `${Number(val ?? 0).toFixed(1)}%`,
    },
  ];

  // Sheet 2: Account Level Receivables Ledger
  const receivableColumns: ExcelColumn<(typeof params.receivables)[0]>[] = [
    { key: "receivableNumber", label: "Contract Number", width: 20 },
    { key: "customerName", label: "Customer Name", width: 25 },
    { key: "customerPhone", label: "Contact Phone", width: 16 },
    { key: "storeName", label: "Store Branch", width: 20 },
    {
      key: "financedAmount",
      label: "Financed Principal (IDR)",
      width: 22,
      format: (val) => Number(val ?? 0),
    },
    {
      key: "totalPaid",
      label: "Total Paid (IDR)",
      width: 20,
      format: (val) => Number(val ?? 0),
    },
    {
      key: "remainingBalance",
      label: "Remaining Balance (IDR)",
      width: 22,
      format: (val) => Number(val ?? 0),
    },
    { key: "paymentTermMonths", label: "Term (Months)", width: 14 },
    { key: "status", label: "Contract Status", width: 18 },
    { key: "firstDueDate", label: "First Due Date", width: 16 },
  ];

  exportMultiSheetExcel({
    filename: `financial_aging_report_${asOf.replace(/-/g, "")}`,
    sheets: [
      {
        sheetName: "Aging Summary",
        title: "STORE MANAGEMENT SYSTEM — CREDIT AGING PORTFOLIO",
        subtitle: `Delinquency risk breakdown and portfolio health as of ${asOf}`,
        metadata: summaryMetadata,
        columns: bucketColumns,
        data: params.buckets,
      },
      {
        sheetName: "Receivable Accounts",
        title: "STORE MANAGEMENT SYSTEM — RECEIVABLE ACCOUNTS LEDGER",
        subtitle: `Itemized customer contract balances and statuses`,
        columns: receivableColumns,
        data: params.receivables,
      },
    ],
  });
}

/**
 * Specialized Excel Workbook Exporter: Stock Balance & Inventory Distribution Report
 */
export interface StockBalanceExportParams {
  storeName?: string;
  asOfDate?: string;
  stockUnits: Array<{
    manufacturerSerial: string | null;
    variantName: string;
    locationType: string;
    availabilityStatus: string;
    notes: string | null;
  }>;
  distribution?: {
    totalUnits: number;
    warehouseUnits: number;
    showroomUnits: number;
    repairAreaUnits: number;
    inTransitUnits: number;
    atCustomerUnits: number;
    availableUnits: number;
    reservedUnits: number;
    unavailableUnits: number;
  };
}

export function exportStockBalanceToExcel(params: StockBalanceExportParams): void {
  const asOf = params.asOfDate || new Date().toISOString().substring(0, 10);
  const storeScope = params.storeName || "Company Wide (All Stores)";

  // Compute distribution from params.distribution if provided, else compute from stockUnits
  const d = params.distribution;
  const total = d ? d.totalUnits : params.stockUnits.length;
  const warehouse = d ? d.warehouseUnits : params.stockUnits.filter((u) => u.locationType === "WAREHOUSE").length;
  const showroom = d ? d.showroomUnits : params.stockUnits.filter((u) => u.locationType === "SHOWROOM").length;
  const repair = d ? d.repairAreaUnits : params.stockUnits.filter((u) => u.locationType === "REPAIR_AREA").length;
  const inTransit = d ? d.inTransitUnits : params.stockUnits.filter((u) => u.locationType === "IN_TRANSIT").length;
  const atCustomer = d ? d.atCustomerUnits : params.stockUnits.filter((u) => u.locationType === "AT_CUSTOMER").length;

  const available = d ? d.availableUnits : params.stockUnits.filter((u) => u.availabilityStatus === "AVAILABLE").length;
  const reserved = d ? d.reservedUnits : params.stockUnits.filter((u) => u.availabilityStatus === "RESERVED").length;
  const unavailable = d ? d.unavailableUnits : params.stockUnits.filter((u) => u.availabilityStatus === "UNAVAILABLE").length;

  // Sheet 1: Distribution Breakdown
  const summaryMetadata: Record<string, string | number> = {
    "Report Name": "Inventory Distribution & Stock Balance Report",
    "Generated As Of": asOf,
    "Store Scope": storeScope,
    "Total Ingested Units": total,
    "Units Available for Sale": available,
    "Units Reserved (Pending Order)": reserved,
    "Units Unavailable (Quarantined/Disposed)": unavailable,
  };

  const locationSummaryData = [
    { location: "Warehouse Storage", count: warehouse, pct: total ? (warehouse / total) * 100 : 0 },
    { location: "Showroom Display", count: showroom, pct: total ? (showroom / total) * 100 : 0 },
    { location: "Repair & Service Area", count: repair, pct: total ? (repair / total) * 100 : 0 },
    { location: "In-Transit (Fleet/Transfer)", count: inTransit, pct: total ? (inTransit / total) * 100 : 0 },
    { location: "At Customer (Delivered/Installment)", count: atCustomer, pct: total ? (atCustomer / total) * 100 : 0 },
  ];

  const locationColumns: ExcelColumn<(typeof locationSummaryData)[0]>[] = [
    { key: "location", label: "Physical Location", width: 32 },
    { key: "count", label: "Unit Count", width: 16 },
    {
      key: "pct",
      label: "% of Inventory",
      width: 18,
      format: (val) => `${Number(val ?? 0).toFixed(1)}%`,
    },
  ];

  // Sheet 2: Itemized Stock Units Ledger
  const unitColumns: ExcelColumn<(typeof params.stockUnits)[0]>[] = [
    {
      key: "manufacturerSerial",
      label: "Serial Number",
      width: 24,
      format: (val) => (val ? String(val) : "Non-serialized"),
    },
    { key: "variantName", label: "Product Variant", width: 32 },
    { key: "locationType", label: "Physical Location", width: 20 },
    { key: "availabilityStatus", label: "Availability Status", width: 20 },
    { key: "notes", label: "Condition / Notes", width: 30 },
  ];

  exportMultiSheetExcel({
    filename: `stock_balance_report_${asOf.replace(/-/g, "")}`,
    sheets: [
      {
        sheetName: "Inventory Summary",
        title: "STORE MANAGEMENT SYSTEM — STOCK BALANCE & DISTRIBUTION",
        subtitle: `Physical inventory breakdown across warehouse, showroom, and transit as of ${asOf}`,
        metadata: summaryMetadata,
        columns: locationColumns,
        data: locationSummaryData,
      },
      {
        sheetName: "Stock Units Ledger",
        title: "STORE MANAGEMENT SYSTEM — SERIALIZED STOCK UNITS",
        subtitle: `Individual unit serialized ledger records and status`,
        columns: unitColumns,
        data: params.stockUnits,
      },
    ],
  });
}

